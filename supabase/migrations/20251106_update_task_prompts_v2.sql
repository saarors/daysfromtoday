-- ========================================================================
-- 验证更新
-- ========================================================================
SELECT 
  goal_type, 
  difficulty, 
  language,
  stage,
  CASE 
    WHEN system_prompt LIKE '%2-5 个%' AND system_prompt LIKE '%40字%' THEN '✅ 已更新为优化版本'
    ELSE '❌ 未更新'
  END as status,
  temperature,
  max_tokens
FROM ai_prompt_library 
WHERE stage = 'task-decomposition'
  AND language = 'zh'
ORDER BY 
  goal_type,
  CASE difficulty 
    WHEN 'easy' THEN 1 
    WHEN 'medium' THEN 2 
    WHEN 'hard' THEN 3 
    WHEN 'expert' THEN 4 
    WHEN 'any' THEN 5
  END;

