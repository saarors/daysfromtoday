#!/bin/bash

echo "╔══════════════════════════════════════════════════════════════════╗"
echo "║                     端口状态检查工具                             ║"
echo "╚══════════════════════════════════════════════════════════════════╝"
echo ""

# 检查常用开发端口
PORTS=(3000 3001 3009 3010 8080)

for PORT in "${PORTS[@]}"; do
  PID=$(lsof -ti:$PORT 2>/dev/null)
  if [ -n "$PID" ]; then
    PROCESS=$(ps -p $PID -o comm= 2>/dev/null)
    echo "✅ 端口 $PORT: 占用中 (PID: $PID, 进程: $PROCESS)"
  else
    echo "⚪ 端口 $PORT: 空闲"
  fi
done

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "当前项目应该运行在: 3009"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"




